export class PixelDisplay {
  constructor(canvas, color = "#35492e") {
    this.ctx = canvas.getContext("2d");
    this.width = canvas.width;
    this.height = canvas.height;
    this.color = color;
  }

  clear() {
    this.ctx.clearRect(0, 0, this.width, this.height);
  }

  rect(x, y, width, height, opacity = 1) {
    this.ctx.fillStyle = this.color;
    this.ctx.globalAlpha = opacity;
    this.ctx.fillRect(Math.round(x), Math.round(y), width, height);
  }

  outline(x, y, width, height, opacity = 1, weight = 1) {
    this.rect(x, y, width, weight, opacity);
    this.rect(x, y + height - weight, width, weight, opacity);
    this.rect(x, y + weight, weight, height - 2 * weight, opacity);
    this.rect(x + width - weight, y + weight, weight, height - 2 * weight, opacity);
  }

  line(x0, y0, x1, y1, opacity = 1, weight = 1) {
    this.ctx.globalAlpha = opacity;
    this.ctx.strokeStyle = this.color;
    this.ctx.lineWidth = weight;
    this.ctx.beginPath();
    this.ctx.moveTo(Math.round(x0) + .5, Math.round(y0) + .5);
    this.ctx.lineTo(Math.round(x1) + .5, Math.round(y1) + .5);
    this.ctx.stroke();
  }

  dots(x0, y0, x1, y1, opacity = .25) {
    const length = Math.max(1, Math.abs(x1 - x0), Math.abs(y1 - y0));
    for (let i = 0; i <= length; i += 4) {
      this.rect(x0 + (x1 - x0) * i / length, y0 + (y1 - y0) * i / length, 2, 1, opacity);
    }
  }

  text(value, x, y, size = 10, opacity = 1) {
    this.ctx.globalAlpha = opacity;
    this.ctx.fillStyle = this.color;
    this.ctx.font = "bold " + size + "px monospace";
    this.ctx.textAlign = "center";
    this.ctx.textBaseline = "middle";
    this.ctx.fillText(String(value), x, y);
  }

  sprite(name, x, y, scale = 2, opacity = 1) {
    const rows = sprites[name] ?? sprites.target;
    const columns = Math.max(...rows.map(row => row.length));
    const startX = Math.round(x - columns * scale / 2);
    const startY = Math.round(y - rows.length * scale / 2);
    this.ctx.fillStyle = this.color;
    this.ctx.globalAlpha = opacity;
    for (let row = 0; row < rows.length; row += 1) {
      for (let col = 0; col < rows[row].length; col += 1) {
        if (rows[row][col] === "#") {
          this.ctx.fillRect(startX + col * scale, startY + row * scale, scale, scale);
        }
      }
    }
  }
}

export function cardIcon(name, color) {
  const canvas = document.createElement("canvas");
  canvas.width = 24;
  canvas.height = 24;
  canvas.setAttribute("aria-hidden", "true");
  new PixelDisplay(canvas, color).sprite(name, 12, 12, 2);
  return canvas;
}
