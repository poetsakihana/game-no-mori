const pathCache = new Map();

function pathOf(d) {
  if (typeof d !== "string") return d;
  if (!pathCache.has(d)) {
    if (pathCache.size >= 2500) pathCache.clear();
    pathCache.set(d, new Path2D(d));
  }
  return pathCache.get(d);
}

function rng(seed) {
  return () => {
    seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
    return seed / 4294967296;
  };
}

function radial(ctx, x, y, radius, color, alpha) {
  const g = ctx.createRadialGradient(x, y, 0, x, y, radius);
  g.addColorStop(0, color + alpha);
  g.addColorStop(1, color + "00");
  return g;
}

function artist(ctx, palette, mode) {
  const color = mode === "color";
  const target = mode === "target";
  const guide = mode === "guide";
  const gradient = ctx.createLinearGradient(-305, -195, 310, 165);
  palette.forEach((tone, i) => gradient.addColorStop(i / (palette.length - 1), tone));
  const secondary = ctx.createLinearGradient(-300, 145, 300, -145);
  palette.forEach((tone, i) => secondary.addColorStop(i / (palette.length - 1), palette[(i + 3) % palette.length]));

  function p(d, width = 2.3, ink = 0, alpha = 1) {
    if (target && alpha < 0.65) return;
    const shape = pathOf(d);
    if (color && width >= 2.8) {
      ctx.globalAlpha = alpha * 0.14;
      ctx.strokeStyle = ink === 0 ? gradient : ink === 1 ? secondary : palette[(ink - 2) % palette.length];
      ctx.lineWidth = width + 6;
      ctx.stroke(shape);
    }
    ctx.globalAlpha = target ? 1 : guide ? alpha * (width >= 3 ? 0.89 : 0.7) : alpha;
    ctx.strokeStyle = target ? "#fff" : guide ? (width >= 3 ? "#655d7a" : "#5a506e") : ink === 0 ? gradient : ink === 1 ? secondary : palette[(ink - 2) % palette.length];
    ctx.lineWidth = width;
    ctx.stroke(shape);
  }

  function fill(d, ink = 0, alpha = 0.16) {
    if (!color) return;
    ctx.fillStyle = ink === 0 ? gradient : ink === 1 ? secondary : palette[(ink - 2) % palette.length];
    ctx.globalAlpha = alpha;
    ctx.fill(pathOf(d));
  }

  function shape(d, ink = 0, width = 3.5, alpha = 0.14) {
    fill(d, ink, alpha);
    p(d, width, ink);
  }

  function e(x, y, rx, ry = rx, rotation = 0, width = 2.3, ink = 0, alpha = 1) {
    const d = new Path2D();
    d.ellipse(x, y, rx, ry, rotation, 0, TAU);
    p(d, width, ink, alpha);
  }

  function dot(x, y, radius = 2, ink = 2, alpha = 0.6) {
    if (target) return;
    const d = new Path2D();
    d.arc(x, y, radius, 0, TAU);
    if (guide) {
      ctx.fillStyle = "#554c70";
      ctx.globalAlpha = alpha;
      ctx.fill(d);
    } else {
      fill(d, ink, alpha);
    }
  }

  function star(x, y, size, ink = 0, alpha = 0.55) {
    const d = new Path2D();
    d.moveTo(x - size, y);
    d.quadraticCurveTo(x, y - size * 0.12, x, y - size);
    d.quadraticCurveTo(x + size * 0.12, y, x + size, y);
    d.quadraticCurveTo(x, y + size * 0.12, x, y + size);
    d.quadraticCurveTo(x - size * 0.12, y, x - size, y);
    d.closePath();
    fill(d, ink, alpha * 0.5);
    p(d, 1.7, ink, alpha);
  }

  function move(x, y, scale, paint, angle = 0, mirror = false) {
    ctx.save();
    ctx.translate(x, y);
    ctx.rotate(angle);
    ctx.scale(mirror ? -scale : scale, scale);
    paint();
    ctx.restore();
  }

  function stroke(points, width = 2.3, ink = 0, alpha = 1) {
    const d = new Path2D();
    points.forEach(([x, y], i) => (i ? d.lineTo(x, y) : d.moveTo(x, y)));
    p(d, width, ink, alpha);
  }
  return { p, fill, shape, e, dot, star, move, stroke };
}

